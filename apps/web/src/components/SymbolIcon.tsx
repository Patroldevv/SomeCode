export type SymbolName = keyof typeof icons;

export function SymbolIcon({
  name,
  className = "",
  style,
}: {
  name: SymbolName;
  className?: string;
  style?: CSSProperties;
}) {
  const Icon = icons[name];
  return <Icon aria-hidden="true" strokeWidth={1.75} className={`size-4 shrink-0 ${className}`} style={style} data-icon={name} />;
}
